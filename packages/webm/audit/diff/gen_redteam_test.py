DESCEND = {EBML, SEGMENT, INFO, TRACKS, 0xAE, 0xE0, 0xE1, CUES, 0xBB, 0xB7, CLUSTER, BLOCKGROUP}


def count_elements(d, start=0, end=None, depth=0):
    """Elements the parser visits: every element at top level and inside the masters it descends into."""
    end = len(d) if end is None else end
    n, maxd = 0, depth
    for i, s, ps, pe in children(d, start, end):
        n += 1
        if i in DESCEND:
            c, md = count_elements(d, ps, pe, depth + 1)
            n += c
            maxd = max(maxd, md)
    return n, maxd


def video_track(num, cp):
    p = uint(TRACK_NUMBER, num) + uint(TRACK_UID, num) + uint(TRACK_TYPE, 1) + elem(CODEC_ID, b"V_VP9")
    p += uint(DEFAULT_DURATION, 33333333) + elem(CODEC_PRIVATE, cp) + elem(VIDEO, uint(PIXEL_W, 320) + uint(PIXEL_H, 240))
    return elem(TRACK_ENTRY, p)


def opus_track(num):
    p = uint(TRACK_NUMBER, num) + uint(TRACK_UID, num) + uint(TRACK_TYPE, 2) + elem(CODEC_ID, b"A_OPUS")
    p += uint(DEFAULT_DURATION, 20000000) + elem(0xE1, elem(0xB5, struct.pack(">d", 48000.0)) + uint(0x9F, 2))
    return elem(TRACK_ENTRY, p)


def limits_sample():
    inf = elem(INFO, uint(SCALE, 1000000) + elem(DURATION, struct.pack(">d", 200.0)) + elem(MUXING_APP, b"audit") +
               elem(0x5741, b"redteam-12"))
    trk = elem(TRACKS, video_track(1, b"\x01\x02\x03\x04\x05") + opus_track(2))
    cues = elem(CUES, elem(CUE_POINT, uint(CUE_TIME, 0) + elem(CUE_TP, uint(CUE_TRACK, 1) + uint(CUE_CPOS, 0))) +
                elem(CUE_POINT, uint(CUE_TIME, 100) + elem(CUE_TP, uint(CUE_TRACK, 1) + uint(CUE_CPOS, 50))))
    xiph3 = sblock(track=2, rel=0, flags=0x82, payload=b"\x02" + b"\x03\x04" + b"A" * 3 + b"B" * 4 + b"C" * 5)
    c0 = cluster(0, sblock(track=1, rel=0, flags=0x80, payload=b"KEY0"), xiph3)
    bg = elem(BLOCKGROUP, elem(BLOCK, b"\x81\x00\x00\x00" + b"PFRAME") + uint(BLOCKDURATION, 33) + elem(REFBLOCK, b"\xdf"))
    c1 = cluster(100, bg, sblock(track=2, rel=1, flags=0x80, payload=b"OPUS"))
    return webm(inf, trk, cues, c0, c1)


def interleaved_av():
    trk = elem(TRACKS, video_track(1, b"") + opus_track(2))
    c0 = cluster(0, sblock(track=1, rel=0, flags=0x80, payload=b"V0"), sblock(track=2, rel=0, flags=0x80, payload=b"A0"))
    # ffmpeg-style interleave: the audio packet at 1001 ms is muxed before the video keyframe at 1000 ms
    c1 = cluster(980, sblock(track=2, rel=21, flags=0x80, payload=b"A1001"), sblock(track=1, rel=20, flags=0x80, payload=b"V1000"))
    return webm(info(), trk, c0, c1)


def truncated_tail():
    full = base(cluster(0, sblock(payload=b"F0"), sblock(rel=20, payload=b"F1")), cluster(40, sblock(payload=b"F2" * 20)))
    return full[:-7]


def cue_positions(n):
    return base(cluster(0, sblock()), elem(CUES, elem(CUE_POINT, uint(CUE_TIME, 1) + elem(CUE_TP, b"") * n)))


def xiph_lace_dd(n=3):
    sizes = b"".join(bytes([4]) for _ in range(n - 1))
    return base(cluster(0, sblock(flags=0x82, payload=bytes([n - 1]) + sizes + b"\x00" * (4 * n))))


def hexs(b):
    h = b.hex()
    parts = [h[i:i + 96] for i in range(0, len(h), 96)]
    return "rt_hex(\n    " + " +\n    ".join(f'"{p}"' for p in parts) + ",\n  )"


S = limits_sample()
E, D = count_elements(S)

def rust(pat, o, p, od):
    f = os.path.join(od, "q.txt")
    open(f, "w").write(f"G {o} {hx(pat)}\nQ {hx(p)}\n")
    return subprocess.run([sys.argv[1], "diff", f], capture_output=True, check=True, text=True).stdout.strip()


def git(content, path, is_dir, od):
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(GIT_CONFIG_GLOBAL="/dev/null", GIT_CONFIG_NOSYSTEM="1")
    repo = os.path.join(od, "r")
    subprocess.run(["rm", "-rf", repo], check=True)
    subprocess.run(["git", "init", "-q", repo], check=True, env=env)
    fp = os.path.join(repo, path)
    os.makedirs(fp if is_dir else os.path.dirname(fp), exist_ok=True)
    if not is_dir:
        open(fp, "w").close()
    open(os.path.join(repo, ".gitignore"), "w").write(content)
    r = subprocess.run(["git", "-c", "core.ignorecase=false", "-c", "core.excludesFile=/dev/null", "-C", repo, "check-ignore", "--no-index", "-v", "-n", "-z", "--stdin"], input=path.encode() + b"\0", capture_output=True, env=env)
    f = r.stdout.split(b"\0")
    return bool(f[0]) and not f[2].startswith(b"!")


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


HEAD = '''///| GENERATED by ../gen_redteam.py -- do not edit. Each expected value was read from the real
///| Rust globset 0.4.21 / ignore 0.4.34 or `git check-ignore`. A FAILURE here is the evidence.
import "glob"

fn opts(o : Int) -> glob::GlobOptions {
  glob::GlobOptions::{
    case_insensitive: (o & 1) != 0,
    literal_separator: (o & 2) != 0,
    backslash_escape: (o & 4) == 0,
    empty_alternates: (o & 8) != 0,
    allow_unclosed_class: (o & 16) != 0,
  }
}

fn expect_glob(pat : String, o : Int, path : String, want : Bool) -> Unit {
  match glob::compile_with(pat, opts(o)) {
    Ok(g) => debug_assert(g.is_match(path) == want, "Glob " + pat + " on " + path + ": oracle says " + want.to_string())
    Err(e) => debug_assert(false, "compile failed: " + e.message)
  }
}

fn expect_set(pat : String, o : Int, path : String, want : Bool) -> Unit {
  match glob::compile_with(pat, opts(o)) {
    Ok(g) =>
    match glob::compile_set_from_globs([g]) {
      Ok(s) => debug_assert(s.is_match(path) == want, "GlobSet " + pat + " on " + path + ": oracle says " + want.to_string())
      Err(e) => debug_assert(false, "set failed: " + e.message)
    }
    Err(e) => debug_assert(false, "compile failed: " + e.message)
  }
}

fn expect_git(content : String, path : String, is_dir : Bool, want : Bool) -> Unit {
  match glob::parse_gitignore(content) {
    Ok(g) => debug_assert(g.is_ignored_with_parents(path, is_dir) == want, "gitignore on " + path + ": git says ignored=" + want.to_string())
    Err(e) => debug_assert(false, "parse_gitignore rejected a file git accepts: " + e.message)
  }
}
'''


def main():
    od = sys.argv[2]
    os.makedirs(od, exist_ok=True)
    out = [HEAD]
    for name, pat, o, p, api in GLOB:
        r = rust(pat, o, p, od)
        want = r[0 if api == "glob" else 1] == "1"
        fn = "expect_glob" if api == "glob" else "expect_set"
        out.append(f'test "{name}" {{\n  {fn}({lit(pat)}, {o}, {lit(p)}, {str(want).lower()})\n}}\n')
    for name, c, p, d in GIT:
        want = git(c, p, d, od)
        out.append(f'test "{name}" {{\n  expect_git({lit(c)}, {lit(p)}, {str(d).lower()}, {str(want).lower()})\n}}\n')
    t = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests", "redteam_test.pion")
    open(t, "w").write("\n".join(out))
    subprocess.run(["pionc", "fmt", t], check=True)


if __name__ == "__main__":
    main()

def write_corpus(path, entries):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for kind, raw in entries:
            f.write(f"{kind}\t{raw}\n")


def main():
    if len(sys.argv) != 2:
        print("usage: gen_data.py <out_dir>", file=sys.stderr)
        return 1
    out_dir = sys.argv[1]
    os.makedirs(out_dir, exist_ok=True)
    write_corpus(os.path.join(out_dir, "corpus_browser.txt"), CORPUS_BROWSER)
    write_corpus(os.path.join(out_dir, "corpus_complex.txt"), CORPUS_COMPLEX)
    vec_path = os.path.join(out_dir, "ietf_vectors.txt")
    with open(vec_path, "w", encoding="utf-8", newline="\n") as f:
        for fn, name, kind, raw_hex, must_fail, can_fail in IETF_VECTORS:
            flags = ("M" if must_fail else "-") + ("C" if can_fail else "-")
            f.write(f"{kind}\t{flags}\t{raw_hex}\t{fn}:{name}\n")
    print(
        f"generated {len(CORPUS_BROWSER)} browser headers, "
        f"{len(CORPUS_COMPLEX)} complex cases, "
        f"{len(IETF_VECTORS)} official IETF vectors in {out_dir}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

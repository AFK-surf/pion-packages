#!/usr/bin/env python3
"""Generate `packages/cookie/src/unicode_noncanon.pion` from Python's `unicodedata`.

Produces a compact sorted table of inclusive Unicode codepoint ranges `[lo, hi]`
(for `cp >= 0x80`) that are NOT stable under UTS #46 (NFKC + lowercase), or are
canonical composition trailing code points / Hangul V/T Jamo that could form
non-NFC decomposed spellings bypassing PSL matching.

Usage:
    python3 packages/cookie/scripts/gen_unicode_noncanon.py          # regenerate src/unicode_noncanon.pion
    python3 packages/cookie/scripts/gen_unicode_noncanon.py --check  # verify byte-for-byte match
"""

import os
import sys
import unicodedata


def enc6(v: int) -> str:
    """Encode a 6-bit integer (0..63) as a single printable ASCII byte avoiding '"' and '\\'."""
    return chr(49 + v) if v >= 44 else chr(48 + v)


def enc24(v: int) -> str:
    return (
        enc6((v >> 18) & 63)
        + enc6((v >> 12) & 63)
        + enc6((v >> 6) & 63)
        + enc6(v & 63)
    )


def build_source() -> str:
    # Exact set of trailing code points participating in Unicode Canonical Composition
    # (no hardcoded whitelist: Thai/Lao tone marks, Arabic vowels, Hebrew points, etc.
    # that are canonical under NFC are preserved).
    comp_second: set[int] = set()
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        d = unicodedata.decomposition(ch)
        if d and not d.startswith("<"):
            parts = d.split()
            if len(parts) == 2:
                a = chr(int(parts[0], 16))
                b = chr(int(parts[1], 16))
                if unicodedata.normalize("NFC", a + b) == ch:
                    comp_second.add(int(parts[1], 16))

    bad: list[int] = []
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        is_noncanon = (
            cp in (0x3002, 0xFF0E, 0xFF61)
            or (0x1161 <= cp <= 0x1175)  # Hangul V jamo
            or (0x11A8 <= cp <= 0x11C2)  # Hangul T jamo
            or cp in comp_second
            or unicodedata.normalize("NFKC", ch).lower() != ch
        )
        if is_noncanon:
            bad.append(cp)

    ranges: list[list[int]] = []
    for cp in bad:
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])

    packed = "".join(enc24(lo) + enc24(hi) for lo, hi in ranges)
    return (
        "///| Compact read-only sorted table of non-canonical Unicode codepoint ranges\n"
        "///| (`cp >= 0x80`) generated by `packages/cookie/scripts/gen_unicode_noncanon.py`\n"
        "///| from Python's `unicodedata` (NFKC + lowercase instability and canonical composition).\n"
        "///| Each entry is 8 ASCII bytes: 4-byte 24-bit `lo` + 4-byte 24-bit `hi` (inclusive).\n"
        "\n"
        "fn unicode_noncanon_range_count() -> Int {\n"
        f"  {len(ranges)}\n"
        "}\n"
        "\n"
        "fn unicode_noncanon_ranges() -> String {\n"
        f'  "{packed}"\n'
        "}\n"
    )


def main() -> int:
    pkg_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = os.path.join(pkg_dir, "src", "unicode_noncanon.pion")
    generated = build_source()

    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        existing = open(out_path, encoding="utf-8").read()
        if existing != generated:
            sys.stderr.write(f"FAIL: {out_path} is out of date; re-run gen_unicode_noncanon.py\n")
            return 1
        print(f"OK: {out_path} matches generator output byte-for-byte ({len(generated)} bytes)")
        return 0

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(generated)
    print(f"Wrote {out_path} ({len(generated)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

// Generates tests/redteam_test.pion from redteam_cases.tsv using the REAL npm `katex` output as the oracle.
// Usage: KATEX_PATH=/path/to/node_modules/katex node gen_tests.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const katex = require(process.env.KATEX_PATH || "katex");
const dir = path.dirname(fileURLToPath(import.meta.url));
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
let out = fs.readFileSync(path.join(dir, "redteam_prelude.pion.in"), "utf8");
out += `\n///| ===== Generated by audit/gen_tests.mjs from audit/redteam_cases.tsv against katex@${katex.version} =====\n`;
for (const line of fs.readFileSync(path.join(dir, "redteam_cases.tsv"), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [name, mode, tex] = line.split("\t");
  const dm = mode === "D";
  let body;
  try {
    const mml = katex.renderToString(tex, { output: "mathml", displayMode: dm });
    body = `  expect_katex_ok("${esc(tex)}", ${dm}, "${esc(mml)}")`;
  } catch (e) {
    body = `  expect_katex_err("${esc(tex)}", ${dm}, "${esc(String(e.message).split("\n")[0])}")`;
  }
  out += `\n///|\ntest "katex-diff: ${name}" {\n${body}\n}\n`;
}
// Layout: KaTeX's own TeX box height/depth (em) of the HTML tree vs Pion `render_layout` root box.
out += `\n///| ===== Layout height/depth oracle: katex.__renderToHTMLTree (TeXbook Appendix G in KaTeX) =====\n`;
let li = 0;
for (const line of fs.readFileSync(path.join(dir, "cases_layout.txt"), "utf8").split("\n")) {
  if (line.length < 2) continue;
  const dm = line.charCodeAt(0) === 68;
  const tex = line.slice(2);
  const tree = katex.__renderToHTMLTree(tex, { displayMode: dm });
  let h = tree.height, d = tree.depth;
  const html = tree.children.find((c) => c.classes && c.classes.includes("katex-html")) || tree;
  for (const b of html.children || []) { h = Math.max(h, b.height); d = Math.max(d, b.depth); }
  li++;
  out += `\n///|\ntest "katex-layout: ${String(li).padStart(2, "0")} ${esc(esc(tex)).slice(0, 60)}" {\n  expect_katex_box("${esc(tex)}", ${dm}, ${h.toFixed(4)}, ${d.toFixed(4)})\n}\n`;
}
fs.writeFileSync(path.join(dir, "tests/redteam_test.pion"), out);
console.log("wrote tests/redteam_test.pion");
